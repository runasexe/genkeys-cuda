inline bool test_stage11_create_public_key(bool verbose) {
    if (verbose) std::cout << "[TEST 11] Complete Ed25519 Public Key Derivation (ed25519_create_public_key): ";
    int *d_res, h_res = 0;
    uint8_t *d_pub, h_pub[32];
    CUDA_CHECK(cudaMalloc(&d_res, sizeof(int)));
    CUDA_CHECK(cudaMalloc(&d_pub, 32));

    test_stage11_kernel<<<1, 1>>>(d_res, d_pub);
    CUDA_CHECK_KERNEL();
    CUDA_CHECK(cudaDeviceSynchronize());
    CUDA_CHECK(cudaMemcpy(&h_res, d_res, sizeof(int), cudaMemcpyDeviceToHost));
    CUDA_CHECK(cudaMemcpy(h_pub, d_pub, 32, cudaMemcpyDeviceToHost));
    CUDA_CHECK(cudaFree(d_res));
    CUDA_CHECK(cudaFree(d_pub));

    if (h_res) {
        if (verbose) std::cout << "PASS" << std::endl;
        return true;
    } else {
        std::cout << "FAIL" << std::endl;
        std::cout << "  Computed Public Key: "; print_hex_bytes_pubkey(h_pub, 32);
        return false;
    }
}

